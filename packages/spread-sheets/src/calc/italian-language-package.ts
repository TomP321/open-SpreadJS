/**
 * Idempotent registration of the built-in Italian package into the core registry. Registration
 * alone never changes parsing (`languagePackages()` stays undefined); activation goes through
 * the public `GC.Spread.CalcEngine.LanguagePackages.languagePackages('it')`, exactly like a
 * host activating 'fr' on the official build.
 */
let registered = false;
export function registerItalianCalcLanguagePackage(): void {
  if (registered) return;
  registered = true;
  registerCalcLanguagePackage(italianLanguagePackage);
}
